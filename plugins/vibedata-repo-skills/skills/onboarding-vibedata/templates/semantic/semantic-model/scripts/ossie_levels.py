"""Generate the dbt test that reports where the data departs from the declared levels.

The model states what a level's keys mean; the data may disagree. This module turns
the declaration into one singular dbt test that *reports* each disagreement (severity
`warn`) and never changes the declaration. Checks, per dataset with levels:

- a row level that is not versioned: its primary key repeats on no two rows;
- every key of a level names the same members as its primary key (one-to-one);
- each hierarchy step: a member rolls up to one parent;
- every aggregate content level: each key value the source carries is a member.

A versioned dimension (Type 2) is checked on its current rows: those are its members
as they are now, and a member's past versions may legitimately differ.

Pure functions: input is a list of parsed documents, output is SQL text.
"""

import json

VENDOR = "VIBEDATA"
HEADER = """-- GENERATED by .agents/skills/semantic-model/scripts/ossie.py level-tests. Do not edit:
-- change the levels in the mapped canonical model and regenerate.
--
-- Reports every place the data departs from the levels the semantic model declares:
-- a key that repeats, a key that names several members, a member with several
-- parents, an aggregate key value that is no member. It warns and never fails a build,
-- because the declaration is the intent and the data is what the tools must handle.
{{ config(severity='warn') }}

"""


def _payload(node):
    for ext in node.get("custom_extensions") or []:
        if isinstance(ext, dict) and ext.get("vendor_name") == VENDOR:
            try:
                data = json.loads(ext.get("data") or "{}")
            except json.JSONDecodeError:
                return {}
            return data if isinstance(data, dict) else {}
    return {}


def _literal(text):
    return "'" + text.replace("'", "''") + "'"


def _key_sql(columns, alias=None):
    cols = [f"{alias}.{c}" if alias else c for c in columns]
    if len(cols) == 1:
        return f"cast({cols[0]} as varchar)"
    return "concat_ws('|', " + ", ".join(f"cast({c} as varchar)" for c in cols) + ")"


class _Dimension:
    """One dataset's levels, resolved to the physical table and columns that hold them."""

    def __init__(self, dataset, payload, tables):
        self.name = dataset["name"]
        self.levels = {lv["name"]: lv for lv in payload.get("levels") or []}
        self.row_level = payload.get("row_level") or {}
        self.hierarchies = payload.get("hierarchies") or []
        self.scd = payload.get("scd") or {}
        base = next(src for src in payload.get("logical_sources") or []
                    if src.get("priority_group", 1) != 0
                    and tables.get(src.get("physical_table"), {}).get("table_type") != "ALIAS")
        self.column = base.get("column_map") or {}
        self.relation = "{{ ref('" + tables[base["physical_table"]]["dbt_model"] + "') }}"

    def columns(self, fields):
        return [self.column[f] for f in fields]

    def primary(self, level_name):
        level = self.levels[level_name]
        return next(k for k in level["keys"] if k.get("primary"))

    def key(self, level_name, key_name):
        if key_name is None:
            return self.primary(level_name)
        return next(k for k in self.levels[level_name]["keys"] if k["name"] == key_name)

    @property
    def rows(self):
        """The rows that are members: current versions for a versioned dimension."""
        if self.row_level.get("versioned") and self.scd.get("is_current"):
            return f"(select * from {self.relation} where {self.column[self.scd['is_current']]})"
        return self.relation


def _dimension_checks(dim):
    out = []
    rows = dim.rows
    if dim.row_level and not dim.row_level.get("versioned"):
        level = dim.row_level["level"]
        pk = _key_sql(dim.columns(dim.primary(level)["fields"]))
        out.append(
            f"select {_literal(f'{dim.name}.{level}: primary key repeats')} as finding,\n"
            f"    {pk} as member\n"
            f"from {rows} as r\ngroup by {pk}\nhaving count(*) > 1")
    for level_name, level in dim.levels.items():
        primary = dim.primary(level_name)
        p_sql = _key_sql(dim.columns(primary["fields"]))
        for key in level["keys"]:
            if key is primary:
                continue
            k_sql = _key_sql(dim.columns(key["fields"]))
            several = f"{dim.name}.{level_name}: key {key['name']} names several members"
            values = f"{dim.name}.{level_name}: member has several values of key {key['name']}"
            out.append(
                f"select {_literal(several)} as finding,\n"
                f"    {k_sql} as member\n"
                f"from {rows} as r\ngroup by {k_sql}\nhaving count(distinct {p_sql}) > 1")
            out.append(
                f"select {_literal(values)} as finding,\n"
                f"    {p_sql} as member\n"
                f"from {rows} as r\ngroup by {p_sql}\nhaving count(distinct {k_sql}) > 1")
    for hier in dim.hierarchies:
        names = hier["levels"]
        for parent, child in zip(names, names[1:]):
            c_sql = _key_sql(dim.columns(dim.primary(child)["fields"]))
            p_sql = _key_sql(dim.columns(dim.primary(parent)["fields"]))
            several = f"{dim.name}.{hier['name']}: {child} rolls up to several {parent} members"
            out.append(
                f"select {_literal(several)} as finding,\n"
                f"    {c_sql} as member\n"
                f"from {rows} as r\ngroup by {c_sql}\nhaving count(distinct {p_sql}) > 1")
    return out


def _aggregate_checks(doc, dims, tables):
    out = []
    relationships = {r["name"]: r for r in doc.get("relationships") or []}
    datasets = {d["name"]: d for d in doc.get("datasets") or []}
    for dataset in doc.get("datasets") or []:
        for src in _payload(dataset).get("logical_sources") or []:
            if src.get("priority_group", 1) != 0:
                continue
            agg = "{{ ref('" + tables[src["physical_table"]]["dbt_model"] + "') }}"
            for ref in src.get("content_levels") or []:
                target = relationships[ref["via"]]["to"] if "via" in ref else dataset["name"]
                dim = dims.get(target)
                if ref.get("level") and dim is not None:
                    fields = dim.key(ref["level"], ref.get("key"))["fields"]
                    member_cols, members = dim.columns(fields), dim.relation
                    level_label = ref["level"]
                else:
                    target_ds = datasets[target]
                    target_payload = _payload(target_ds)
                    base = next(s for s in target_payload.get("logical_sources") or []
                                if s.get("priority_group", 1) != 0
                                and tables[s["physical_table"]].get("table_type") != "ALIAS")
                    fields = target_ds.get("primary_key") or []
                    member_cols = [base["column_map"][f] for f in fields]
                    members = "{{ ref('" + tables[base["physical_table"]]["dbt_model"] + "') }}"
                    level_label = "row"
                key_cols = ref["key_columns"]
                match = " and ".join(f"d.{m} = a.{k}" for m, k in zip(member_cols, key_cols))
                present = " and ".join(f"a.{k} is not null" for k in key_cols)
                label = f"{dataset['name']}.{src['name']}: {ref.get('via', target)} {level_label} key is no member"
                out.append(
                    f"select distinct {_literal(label)} as finding,\n"
                    f"    {_key_sql(key_cols, 'a')} as member\n"
                    f"from {agg} as a\n"
                    f"where {present}\n"
                    f"    and not exists (select 1 from {members} as d where {match})")
    return out


def generate(docs):
    """SQL for every document in `docs` (parsed dicts), shared dimensions checked once."""
    dimension_sql, aggregate_sql, seen = [], [], set()
    for doc in docs:
        model = _payload(doc)
        tables = {t["name"]: t for t in model.get("physical_tables") or []}
        dims = {}
        for dataset in doc.get("datasets") or []:
            payload = _payload(dataset)
            if payload.get("levels"):
                dims[dataset["name"]] = _Dimension(dataset, payload, tables)
        for name in sorted(dims):
            if name not in seen:
                seen.add(name)
                dimension_sql.extend(_dimension_checks(dims[name]))
        aggregate_sql.extend(_aggregate_checks(doc, dims, tables))
    parts = dimension_sql + aggregate_sql
    if not parts:
        return HEADER + "select null as finding, null as member where false\n"
    return HEADER + "\n\nunion all\n\n".join(parts) + "\n"
